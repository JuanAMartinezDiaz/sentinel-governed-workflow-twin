"""Generate scenario descriptions from the catalog and deterministic engine.

No evidence UUIDs, timestamps, permits, or secrets are published in static assets.
"""

import argparse
from html import escape
import json
from pathlib import Path

from api.demo import run_scenario
from api.scenarios import SCENARIOS

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- BEGIN SYNTHETIC SCENARIOS -->"
END = "<!-- END SYNTHETIC SCENARIOS -->"
BUTTON_START = "<!-- BEGIN GENERATED SCENARIO BUTTONS -->"
BUTTON_END = "<!-- END GENERATED SCENARIO BUTTONS -->"


def scenario_summary():
    count = len(SCENARIOS)
    rows = [
        START,
        f"The API supports **{count} fixed synthetic scenarios**, all **{count} available in Decision X-Ray**. No scenarios are API-only.",
        "",
        "| API scenario | Visual selection | Decision | Simulated execution |",
        "|---|---|---|---|",
    ]
    for name, spec in SCENARIOS.items():
        result = run_scenario(name)
        rows.append(
            f"| `{name}` | {spec['visual']['label']} | `{result['decision']}` | "
            f"`{result['evidence'][1]['execution_status']}` |"
        )
    return "\n".join([*rows, END])


def browser_scenarios():
    catalog = {}
    for name, spec in SCENARIOS.items():
        result = run_scenario(name)
        trace = (
            "ILLUSTRATIVE REFERENCE TRACE (fixed synthetic inputs)\n"
            f"{spec['action_class']} / {spec['tool_name']} / {spec['risk_tier'].name} / "
            f"confidence {spec['confidence']:.2f}\n\n"
            + "\n".join(f"[{s['status']}] {s['check']} — {s['detail']}" for s in result['trace'])
            + f"\n\nDISPOSITION: {result['decision']}"
            + f"\nGOVERNED EXECUTION: {result['evidence'][1]['execution_status']}"
        )
        if result['approval_note']:
            trace += "\n" + result['approval_note']
        visual = spec['visual']
        catalog[visual['key']] = {
            **visual, 'apiScenario': name, 'disp': result['decision'], 'trace': trace,
        }
    return catalog


def replace_block(text, start, end, replacement):
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError(f"Expected exactly one {start} / {end} block")
    before, rest = text.split(start)
    _, after = rest.split(end)
    return before + replacement + after


def generated_files(root=ROOT):
    summary = scenario_summary()
    files = {}
    for name in ('README.md', 'RUN_DEMO.md'):
        files[name] = replace_block((root / name).read_text(), START, END, summary)
    buttons = [BUTTON_START]
    for spec in SCENARIOS.values():
        visual = spec['visual']
        active = ' active' if visual['key'] == 'high' else ''
        buttons.append(
            f'<button class="scenario-btn{active}" data-scenario="{escape(visual["key"], quote=True)}">'
            f'<b>{escape(visual["label"])}</b><small>{escape(visual["sub"])}</small></button>'
        )
    buttons.append(BUTTON_END)
    files['docs/index.html'] = replace_block(
        (root / 'docs/index.html').read_text(), BUTTON_START, BUTTON_END, '\n'.join(buttons)
    )
    files['docs/scenarios.mjs'] = (
        '// Generated by python -m scripts.sync_demo_scenarios; do not edit.\n'
        'export const scenarios = ' + json.dumps(browser_scenarios(), indent=2, ensure_ascii=False) + ';\n'
    )
    return files


def check_pr_body(body):
    """Fail CI when a declared API summary is missing, duplicated or outdated."""
    if body.count(START) != 1 or body.count(END) != 1 or scenario_summary() not in body:
        raise ValueError('PR scenario summary is missing or stale; copy --pr-summary output into the description')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--pr-summary', action='store_true')
    parser.add_argument('--github-event', type=Path)
    args = parser.parse_args()
    if args.pr_summary:
        print(scenario_summary())
        return
    stale = []
    for name, content in generated_files().items():
        path = ROOT / name
        if not path.exists() or path.read_text() != content:
            stale.append(name)
            if not args.check:
                path.write_text(content, encoding='utf-8')
    if args.check and stale:
        parser.exit(1, 'Scenario artifacts are stale: ' + ', '.join(stale) + '\n')
    if args.github_event:
        event = json.loads(args.github_event.read_text())
        pr = event.get('pull_request')
        if pr:
            body = pr.get('body') or ''
            # PR #2 establishes the contract. Subsequent PRs opt in by including
            # the summary marker; unrelated PRs do not need an API summary.
            if pr.get('number') == 2 or START in body:
                try:
                    check_pr_body(body)
                except ValueError as error:
                    parser.exit(1, str(error) + '\n')
    print('Scenario contract is synchronized.' if args.check else 'Scenario artifacts regenerated.')


if __name__ == '__main__':
    main()
